/**
 * Fills the reset form hydration-safe: the inputs are React-controlled, so a
 * value typed before hydration is dropped on the first re-render. Wait for the
 * field, fill both inputs and verify the value actually stuck.
 */
async function fillResetForm(page, password) {
  await page.locator('input[name="password"]').first().waitFor({ state: "visible", timeout: 20000 });
  await page.waitForTimeout(700);
  for (let attempt = 0; attempt < 3; attempt++) {
    await page.fill('input[name="password"]', password);
    await page.fill('input[name="passwordConfirm"]', password);
    if ((await page.inputValue('input[name="password"]')) === password) return;
    await page.waitForTimeout(500);
  }
  throw new Error("password field did not retain the typed value");
}

