const visibleText = (page, text) => page.getByText(text, { exact: false }).filter({ visible: true }).first();
async function isVisible(page, text, timeout = 0) {
  if (timeout > 0) {
    try {
      await visibleText(page, text).waitFor({ state: "visible", timeout });
      return true;
    } catch {
      return false;
    }
  }
  return visibleText(page, text).isVisible();
}
