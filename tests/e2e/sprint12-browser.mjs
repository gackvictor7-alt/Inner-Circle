async function newContext({ mobile = false, locale = "de", theme = "light", storageState } = {}) {
  const context = await browser.newContext({
    viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 },
    deviceScaleFactor: mobile ? 2 : 1,
    isMobile: mobile,
    hasTouch: mobile,
    colorScheme: theme,
    locale: locale === "de" ? "de-DE" : "en-US",
    storageState,
  });
  await context.addInitScript(
    ([loc, th]) => {
      try {
        localStorage.setItem("ic-locale", loc);
        localStorage.setItem("ic-theme", th);
      } catch {
        /* storage unavailable – defaults apply */
      }
    },
    [locale, theme],
  );
  return context;
}

