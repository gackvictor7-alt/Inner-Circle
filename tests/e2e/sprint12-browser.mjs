async function waitForCode(email) {
  for (let attempt = 0; attempt < 30; attempt++) {
    const rows = sql(`select body from DevOutbox where "to" = '${email}' order by createdAt desc limit 1`);
    const match = rows[0]?.body?.match(/\b(\d{6})\b/);
    if (match) return match[1];
    await sleep(500);
  }
  throw new Error(`no verification code for ${email}`);
}

