/**
 * Sprint 13 – browser end-to-end check: unified profile save + photo upload.
 *
 * Runs against the REAL Worker build (`npm run cf:preview`: workerd + local D1
 * + local R2 emulation) with clearly labelled test accounts. It is NOT part of
 * `npm test` and adds no dependency to the project: the browser packages live
 * outside the repository.
 *
 *   mkdir -p /tmp/pw && cd /tmp/pw && npm i playwright-core @sparticuz/chromium
 *   PW_MODULES=/tmp/pw/node_modules BASE_URL=http://127.0.0.1:8787 \
 *     node tests/e2e/profile-save-upload.mjs
 *
 * Requirements (see docs/08-testing.md): fresh, isolated LOCAL D1, migrated +
 * bootstrapped; `.dev.vars` with ENABLE_DEV_OUTBOX=true (verification codes are
 * read from the local dev outbox). The script only ever touches the LOCAL
 * database (`wrangler d1 execute --local`) and refuses to run against anything
 * but localhost.
 *
 * What is verified:
 *   1. ONE save button – profile fields, interests & goals persist together
 *      ("Speichern" submits the unified form; success banner `?saved=all`).
 *   2. Everything survives a hard reload (fields, interests, goals, photo).
 *   3. Photo upload ("Foto auswählen"): preview, client-side rejection of an
 *      oversized file, PNG and WebP accepted, replaced uploads cleaned up,
 *      removal really clears the photo, URL alternative still works.
 *   4. The stored photo is served from `/api/media/…` (HTTP 200, correct type)
 *      and appears in the app shell, on the own profile page, on the public
 *      profile page and – via a second, beta-enabled account – in Discover.
 *
 * Output: screenshots in preview/sprint13/, results as JSON in $E2E_OUT
 * (default /tmp/e2e-profile-results-<run>.json). Exit code 1 if any check
 * fails.
 */
