  await a.locator('button[type="submit"]').filter({ hasText: "Profil speichern" }).click();
  await a.waitForURL(/saved=all/, { timeout: 45000 });
  const fionaUrl = sql(`select "avatarUrl" from "Profile" p join "User" u on u."id" = p."userId" where u."email" = '${emails.foto}';`)[0]?.avatarUrl;
  check(Boolean(fionaUrl) && fionaUrl.includes("/api/media/avatars/"), "Fiona's photo active again", `db=${fionaUrl}`);
