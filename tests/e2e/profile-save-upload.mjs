  check(viaUrl[0]?.avatarUrl === "https://images.example/fiona.jpg", "photo-by-URL alternative still saves", `db=${viaUrl[0]?.avatarUrl}`);
  await a.fill('input[name="avatarUrl"]', "");
  await a.locator('button[type="submit"]').filter({ hasText: "Profil speichern" }).click();
  await a.waitForURL(/saved=all/, { timeout: 45000 });

